    html = page(sample)
    if sample:
        leaks = [s for s in SECRETS if s in html]
        assert not leaks, leaks
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write(html)
    print(rel, len(html), "bytes")
