"""Build the lab reference annex in two editions from one source.

    python3 -I lab/annex/_build.py

    annex/_lab-template/index.html   the full annex, private (underscore)
    lab/annex/sample/index.html      the redacted sample, public, noindex

R(text, size) is the one place the editions differ: the template prints
the text, the sample prints an empty redaction mark. The mark removes the
content, it does not cover it, so nothing redacted reaches the sample's
file. The build asserts that.
"""
